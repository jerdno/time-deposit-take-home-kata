-- Assumption (ticket 5): tables and columns use PostgreSQL's snake_case (time_deposits.plan_type,
-- withdrawals.time_deposit_id) for the README's timeDeposits.planType and withdrawals.timeDepositId.
-- The API keeps the README's camelCase names.
-- Assumption (ticket 5): created_at is when the row was inserted, not when the Time Deposit was opened.
-- Assumption (ticket 5): days is stored as-is; the application never advances it.

CREATE TABLE time_deposits (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Assumption (ticket 5): no CHECK constraint. An unknown Plan Type is bad data the application must survive and
    -- still list, not reject.
    plan_type  VARCHAR(50)    NOT NULL,
    days       INTEGER        NOT NULL,
    balance    NUMERIC(19, 2) NOT NULL,
    version    BIGINT         NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE TABLE withdrawals (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_deposit_id INTEGER        NOT NULL REFERENCES time_deposits (id),
    amount          NUMERIC(19, 2) NOT NULL,
    date            DATE           NOT NULL,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now()
);

-- Withdrawals are loaded for a page of Time Deposits at once (WHERE time_deposit_id IN (...)).
CREATE INDEX withdrawals_time_deposit_id_idx ON withdrawals (time_deposit_id);
